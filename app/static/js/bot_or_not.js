function showIntroError(message) {
  if (!el.introImageError) {
    return;
  }

  el.introImageError.textContent =
    message;

  el.introImageError.style.display =
    "block";
}

function clearIntroError() {
  if (!el.introImageError) {
    return;
  }

  el.introImageError.textContent = "";

  el.introImageError.style.display =
    "none";
}

function setIntroductionImage(slide) {
  if (!el.introImg) {
    console.error(
      'The HTML element with id="introImg" was not found.'
    );

    return;
  }

  clearIntroError();

  el.introImg.classList.remove("hidden");
  el.introImg.style.display = "block";

  el.introImg.onload = () => {
    el.introImg.classList.remove("hidden");
    el.introImg.style.display = "block";

    clearIntroError();

    console.log(
      "Introduction image loaded:",
      slide.image,
      `${el.introImg.naturalWidth} × ${el.introImg.naturalHeight}`
    );
  };

  el.introImg.onerror = () => {
    el.introImg.style.display = "none";

    const message =
      `Introduction image failed to load: ${slide.image}`;

    showIntroError(message);

    console.error(message);
  };

  el.introImg.alt = slide.alt;

  /*
    Remove the previous URL before setting the new one.
    This helps the browser fire the loading event reliably.
  */

  el.introImg.removeAttribute("src");

  requestAnimationFrame(
    () => {
      el.introImg.src = slide.image;
    }
  );
}

function renderIntroduction() {
  const slide =
    introductionSlides[introIndex];

  if (!slide || !el.introView) {
    gameStartRequested = true;

    if (gameDataReady) {
      beginGame();
    }

    return;
  }

  if (el.introHeading) {
    el.introHeading.textContent =
      slide.heading;
  }

  if (el.introText) {
    el.introText.textContent =
      slide.text;
  }

  setIntroductionImage(slide);

  if (el.introProgress) {
    el.introProgress.textContent =
      `Introduction ${introIndex + 1} of ${introductionSlides.length}`;
  }

  const isLastSlide =
    introIndex ===
    introductionSlides.length - 1;

  if (el.introNextBtn) {
    el.introNextBtn.disabled = false;

    el.introNextBtn.textContent =
      isLastSlide
        ? "Start Game →"
        : "Next →";
  }

  const nextSlide =
    introductionSlides[introIndex + 1];

  if (nextSlide) {
    preload(nextSlide.image).catch(
      error => {
        console.error(
          "Could not preload the next introductory image:",
          error
        );
      }
    );
  }
}

function advanceIntroduction() {
  if (!introActive) {
    return;
  }

  if (
    introIndex <
    introductionSlides.length - 1
  ) {
    introIndex += 1;

    renderIntroduction();

    return;
  }

  requestGameStart();
}

function requestGameStart() {
  gameStartRequested = true;

  if (gameLoadFailed) {
    if (el.introText) {
      el.introText.textContent =
        "The game could not be loaded. Check that Flask is running and reload the page.";
    }

    if (el.introNextBtn) {
      el.introNextBtn.disabled = true;

      el.introNextBtn.textContent =
        "Game unavailable";
    }

    return;
  }

  if (!gameDataReady) {
    if (el.introText) {
      el.introText.textContent =
        "The game images are still being prepared.";
    }

    if (el.introNextBtn) {
      el.introNextBtn.disabled = true;

      el.introNextBtn.textContent =
        "Loading game…";
    }

    return;
  }

  beginGame();
}

async function beginGame() {
  if (gameStarted) {
    return;
  }

  if (!gameDataReady) {
    gameStartRequested = true;

    return;
  }

  gameStarted = true;
  introActive = false;

  document.body.classList.remove(
    "intro-active"
  );

  if (el.introView) {
    el.introView.classList.add(
      "hidden"
    );
  }

  if (el.gameGrid) {
    el.gameGrid.classList.remove(
      "hidden"
    );
  }

  window.scrollTo({
    top: 0,
    behavior: "smooth"
  });

  /*
    The first game image is displayed only
    after both introductory slides.
  */

  await showCurrent();

  const firstChoiceButton =
    document.querySelector(
      'button[data-choice="child"]'
    );

  if (firstChoiceButton) {
    firstChoiceButton.focus();
  }
}

/* =========================================================
   FULL-SCREEN IMAGE OVERLAY
   ========================================================= */

function openOverlay(src) {
  if (!src) {
    return;
  }

  const overlay =
    document.createElement("div");

  const image =
    document.createElement("img");

  overlay.className =
    "imgOverlay";

  image.src = src;
  image.alt = "Full screen";

  overlay.appendChild(image);

  document.body.appendChild(
    overlay
  );

  function closeOverlay() {
    window.removeEventListener(
      "keydown",
      handleOverlayKey,
      true
    );

    overlay.remove();
  }

  function handleOverlayKey(event) {
    if (event.key === "Escape") {
      event.preventDefault();
      event.stopImmediatePropagation();

      closeOverlay();
    }
  }

  overlay.addEventListener(
    "click",
    closeOverlay
  );

  window.addEventListener(
    "keydown",
    handleOverlayKey,
    true
  );
}

