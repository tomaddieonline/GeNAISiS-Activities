function normaliseChoice(value) {
  return value === "artist"
    ? "pro"
    : value;
}

function niceLabel(value) {
  const normalised =
    normaliseChoice(value);

  if (normalised === "child") {
    return "Child";
  }

  if (normalised === "pro") {
    return "Professional Artist";
  }

  if (normalised === "ai") {
    return "AI";
  }

  if (normalised === "skip") {
    return "Skipped";
  }

  return value || "—";
}

function nowMs() {
  return Date.now();
}

function toast(message) {
  if (!el.toast) {
    return;
  }

  el.toast.textContent = message;
  el.toast.classList.add("show");

  clearTimeout(toast._timer);

  toast._timer = setTimeout(
    () => {
      el.toast.classList.remove("show");
    },
    1200
  );
}

function setStatus(message) {
  if (el.microStatus) {
    el.microStatus.textContent = message;
  }
}

function setScorePill() {
  if (!el.pillScore) {
    return;
  }

  el.pillScore.textContent =
    scoredCount === 0
      ? "Score: —"
      : `Score: ${score} / ${scoredCount}`;
}

function setProgress() {
  if (el.pillProgress) {
    el.pillProgress.textContent =
      `${Math.min(index + 1, images.length)} / ${images.length}`;
  }

  const percentage = images.length
    ? (
        Math.min(index, images.length) /
        images.length
      ) * 100
    : 0;

  if (el.progressFill) {
    el.progressFill.style.width =
      `${percentage}%`;
  }
}

async function fetchJSON(url) {
  const response = await fetch(
    url,
    {
      headers: {
        Accept: "application/json"
      }
    }
  );

  if (!response.ok) {
    throw new Error(
      `HTTP ${response.status}`
    );
  }

  return response.json();
}

function preload(src) {
  return new Promise(
    (resolve, reject) => {
      const image = new Image();

      image.onload = () => {
        resolve(true);
      };

      image.onerror = () => {
        reject(
          new Error(
            `Failed to load image: ${src}`
          )
        );
      };

      image.src = src;
    }
  );
}

function lockChoices(locked) {
  canAnswer =
    !locked &&
    gameStarted &&
    !introActive;

  el.buttons.forEach(
    button => {
      button.disabled = locked;
    }
  );

  if (el.skipBtn) {
    el.skipBtn.disabled = locked;
  }
}

function enableSkipOnly() {
  canAnswer = true;

  el.buttons.forEach(
    button => {
      button.disabled = true;
    }
  );

  if (el.skipBtn) {
    el.skipBtn.disabled = false;
  }
}

function showSkeleton(show) {
  if (!el.skeleton || !el.frame) {
    return;
  }

  el.skeleton.classList.toggle(
    "hidden",
    !show
  );

  el.frame.classList.toggle(
    "hidden",
    show
  );
}

